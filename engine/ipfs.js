// Coin metadata: the image and the JSON the create instruction points at.
//
// pump.fun's keyless uploader (pump.fun/api/ipfs) is gone: since ~2026-10 its site uploads
// through frontend-api-v3 /ipfs/token-metadata, which needs a signed-in pump.fun session.
// So by default the engine hosts the metadata itself, under the SITE's address
// (`<site>/api/m/<key>.json`): the site forwards /api to the engine, so the URI written into
// the coin stays valid even if the engine moves to another host. With PINATA_JWT set, the
// image and JSON are pinned to IPFS instead (permanent, independent of us).
import { randomUUID } from 'crypto'
import { existsSync, mkdirSync, writeFileSync, readFileSync, unlinkSync } from 'fs'
import { join } from 'path'
import { config } from './config.js'

const PIN_FILE = 'https://api.pinata.cloud/pinning/pinFileToIPFS'
const PIN_JSON = 'https://api.pinata.cloud/pinning/pinJSONToIPFS'
const GATEWAY = 'https://pump.mypinata.cloud/ipfs'

export const MAX_IMAGE_BYTES = 4 * 1024 * 1024
const EXT = { 'image/png': 'png', 'image/jpeg': 'jpg', 'image/gif': 'gif', 'image/webp': 'webp' }

/** What the bytes really are, from their first bytes. A declared type is never trusted. */
export function sniffImage(buf) {
  if (!buf || buf.length < 12) return null
  if (buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47) return 'image/png'
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return 'image/jpeg'
  if (buf.slice(0, 4).toString('ascii') === 'GIF8') return 'image/gif'
  if (buf.slice(0, 4).toString('ascii') === 'RIFF' && buf.slice(8, 12).toString('ascii') === 'WEBP') return 'image/webp'
  return null
}

export function checkImage(file) {
  if (!file?.buffer?.length) throw Object.assign(new Error('no image'), { code: 400 })
  if (file.buffer.length > MAX_IMAGE_BYTES) throw Object.assign(new Error('image must be under 4 MB'), { code: 400 })
  const type = sniffImage(file.buffer)
  if (!type) throw Object.assign(new Error('image must be PNG, JPEG, GIF or WebP'), { code: 400 })
  return type
}

const metaDir = () => join(config.dataDir, 'meta')
export const metaBase = () => `${(config.metaBaseUrl || config.siteUrl).replace(/\/$/, '')}/api/m`

/** Point any IPFS URL at a gateway a browser will actually render. */
export function onGateway(url) {
  const cid = /\/ipfs\/([A-Za-z0-9]+)/.exec(String(url || ''))
  return cid ? `${GATEWAY}/${cid[1]}` : url
}

function metadataJson(d, image) {
  return {
    name: d.name || '', symbol: d.symbol || '', description: d.description || '', image, showName: true,
    createdOn: config.siteUrl,
    ...(d.telegram ? { telegram: d.telegram } : {}),
    ...(d.website ? { website: d.website } : {}),
    ...(d.twitter ? { twitter: d.twitter } : {}),
  }
}

/* ---------------- hosted by the engine ---------------- */

function selfHost(file, type, d) {
  if (!existsSync(metaDir())) mkdirSync(metaDir(), { recursive: true })
  const key = randomUUID().replace(/-/g, '').slice(0, 20)
  const imgName = `${key}.${EXT[type]}`
  writeFileSync(join(metaDir(), imgName), file.buffer)
  const image = `${metaBase()}/${imgName}`
  writeFileSync(join(metaDir(), `${key}.json`), JSON.stringify(metadataJson(d, image)))
  return { uri: `${metaBase()}/${key}.json`, image }
}

/** Serve a hosted file. Names are generated by us, so anything else is refused. */
export function readHosted(name) {
  if (!/^[a-f0-9]{20}\.(json|png|jpg|gif|webp)$/.test(String(name))) return null
  const p = join(metaDir(), name)
  if (!existsSync(p)) return null
  const ext = name.split('.').pop()
  const type = ext === 'json' ? 'application/json' : Object.keys(EXT).find(k => EXT[k] === ext)
  return { body: readFileSync(p), type }
}

/* ---------------- Pinata, when a key is configured ---------------- */

async function pin(url, body, headers = {}) {
  const res = await fetch(url, { method: 'POST', headers: { Authorization: `Bearer ${config.pinataJwt}`, ...headers }, body, signal: AbortSignal.timeout(60_000) })
  const text = await res.text()
  let json
  try { json = JSON.parse(text) } catch { throw new Error(`pinata: non-JSON reply (${res.status})`) }
  if (!res.ok || !json.IpfsHash) throw new Error(`pinata: ${json?.error?.details || json?.error || res.status}`)
  return `${GATEWAY}/${json.IpfsHash}`
}

async function viaPinata(file, type, d) {
  const form = new FormData()
  form.append('file', new Blob([file.buffer], { type }), `coin.${EXT[type]}`)
  const image = await pin(PIN_FILE, form)
  const uri = await pin(PIN_JSON, JSON.stringify({ pinataContent: metadataJson(d, image) }), { 'Content-Type': 'application/json' })
  return { uri, image }
}

/** Store the image and the metadata, and return the URI the create instruction needs. */
export async function uploadMetadata(file, details) {
  const type = checkImage(file)
  if (config.pinataJwt) {
    try { return await viaPinata(file, type, details) } catch (e) { console.warn('[meta] pinata failed, hosting it ourselves:', String(e.message).slice(0, 120)) }
  }
  return selfHost(file, type, details)
}

/** Delete what selfHost wrote for a launch that never went out. Pinned files are left alone. */
export function removeHosted(meta) {
  for (const url of [meta?.uri, meta?.image]) {
    const name = String(url || '').startsWith(metaBase()) ? String(url).split('/').pop() : null
    if (!name || !/^[a-f0-9]{20}\.(json|png|jpg|gif|webp)$/.test(name)) continue
    try { unlinkSync(join(metaDir(), name)) } catch {}
  }
}
